package scaffold

import (
	"fmt"
	"strings"

	"github.com/buxee/alix-ai/internal/readiness/scan"
	"gopkg.in/yaml.v3"
)

// scaffoldOut is one file to write, relative to OUTDIR.
type scaffoldOut struct {
	Path    string
	Content string
}

// The marker every YAML file starts with, and the one every Markdown file starts with.
const (
	scaffoldYAMLMarker = "# DRAFT - generated by `alixai readiness scan --scaffold` from verified readiness findings.\n" +
		"# NOT SIGNED and NOT an installable package: the package loader refuses it as unsigned, and an installed copy would be quarantined.\n" +
		"# Every TODO(owner) marker is a fact or a decision only the application owner can supply. Nothing here says a capability is safe.\n"
	scaffoldMDMarker = "<!-- DRAFT - generated by `alixai readiness scan --scaffold`. Stub only: no prose was generated. " +
		"The application owner writes and signs the documentation. -->\n"
)

// scaffoldQuote renders a string as a YAML scalar. Every value that came from the project goes through it.
func scaffoldQuote(s string) string {
	b, err := yaml.Marshal(s)
	if err != nil {
		return `"invalid"`
	}
	return strings.TrimRight(string(b), "\n")
}

// scaffoldComment makes text safe inside one comment line: no control character, no line break, bounded.
func scaffoldComment(s string) string {
	s = scan.ScanRedact(s)
	var b strings.Builder
	for _, r := range s {
		if r < 0x20 || r == 0x7f || r == 0x85 || r == 0x2028 || r == 0x2029 {
			r = ' '
		}
		b.WriteRune(r)
	}
	out := strings.Join(strings.Fields(b.String()), " ")
	if len(out) > 300 {
		out = out[:300]
		for len(out) > 0 && out[len(out)-1] >= 0x80 {
			out = out[:len(out)-1]
		}
	}
	return out
}

func scaffoldRefLines(prefix string, refs []scaffoldFact) string {
	var b strings.Builder
	for _, r := range refs {
		b.WriteString(prefix + "verified in: " + scaffoldComment(r.ref()) + "\n")
	}
	return b.String()
}

func scaffoldRender(p scaffoldPlan) []scaffoldOut {
	var out []scaffoldOut
	out = append(out, scaffoldOut{"alixai.yaml", scaffoldManifest(p)})
	for _, c := range p.caps {
		out = append(out, scaffoldOut{c.File, scaffoldCapabilityYAML(p, c)})
	}
	out = append(out, scaffoldOut{"documentation/index.yaml", scaffoldDocIndex(p)})
	for _, c := range p.caps {
		out = append(out, scaffoldOut{c.Doc, scaffoldCapabilityDoc(c)})
	}
	for _, r := range p.rag {
		out = append(out, scaffoldOut{r.File, scaffoldRAGYAML(r)})
	}
	out = append(out, scaffoldOut{"DRAFT-TODO.md", scaffoldTodo(p)})
	return out
}

// scaffoldManifest is alixai.yaml. It is schema-valid on purpose, so that the loader goes on to the signature check and reports
// signature.missing; every value that is not a verified fact is a TODO(owner) marker, a reserved .invalid host, a draft version or the
// strictest choice.
func scaffoldManifest(p scaffoldPlan) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	b.WriteString(scaffoldYAMLMarker)
	b.WriteString("#\n# What is verified here: the capability ids and RAG source ids (each with the file it was found in), and the transport.\n")
	b.WriteString("# Everything else is a placeholder. Hosts ending in .invalid never resolve; replace them. See DRAFT-TODO.md.\n")
	w("format: alixai.application-package/v1\n")
	w("application:\n")
	if p.appIDGiven {
		w("  id: %s # from -app, supplied by the operator\n", scaffoldQuote(p.appID))
	} else {
		w("  id: %s # TODO(owner): the application id\n", scaffoldQuote(p.appID))
	}
	w("  name: %s\n", scaffoldQuote("TODO(owner): application name"))
	w("  version: 0.0.0-draft # TODO(owner): the application version\n")
	w("package:\n  version: 0.0.0-draft # TODO(owner): the package version\n")
	w("compatibility:\n  alixai_core:\n    min: 1.0.0 # TODO(owner): confirm the AlixAI core range this package was written for\n    max_exclusive: 2.0.0\n")
	w("endpoints:\n")
	b.WriteString(scaffoldRefLines("  # ", p.transportBy))
	if len(p.transportBy) == 0 {
		w("  # The transport could not be determined from verified evidence: mcp is a placeholder. TODO(owner)\n")
	}
	switch p.transport {
	case "openapi":
		w("  todo-endpoint:\n    transport: openapi\n    base_url: https://todo-owner-sets-the-url.invalid\n    spec: schemas/todo-endpoint.openapi.yaml\n    adapter_config: schemas/adapters/todo-endpoint.yaml\n")
	case "native":
		w("  todo-endpoint:\n    transport: native\n    bridge: %s # the language of the verified bridge file; TODO(owner): confirm\n", p.bridge)
		w("    ipc: # local IPC only; TODO(owner): the socket, pipe or loopback port the bridge listens on (port 0 is never reachable)\n")
		w("      kind: loopback_tcp\n      address: 127.0.0.1:0\n")
		w("    adapter_config: schemas/adapters/todo-endpoint.yaml # TODO(owner): server, key (id and an env: or file: ref) and management operations\n")
	default:
		w("  todo-endpoint:\n    transport: mcp\n    url: https://todo-owner-sets-the-url.invalid/mcp\n    adapter_config: schemas/adapters/todo-endpoint.yaml\n")
	}
	w("context_exchange: # TODO(owner): how the host application hands AlixAI the identity context\n")
	if p.transport == "native" {
		w("  mode: local_ipc # a native bridge authenticates its peer over local IPC\n  issuer: todo-owner-sets-the-issuer\n  audience: todo-owner-sets-the-audience\n  key_ids:\n  - todo-owner-key-id\n")
	} else {
		w("  mode: context_token\n  issuer: https://todo-owner-sets-the-issuer.invalid\n  audience: todo-owner-sets-the-audience\n  key_ids:\n  - todo-owner-key-id\n")
	}
	w("tenancy: # TODO(owner): the tenant and workspace model of the application\n")
	w("  tenant:\n    label: %s\n    description: %s\n", scaffoldQuote("TODO(owner): tenant"), scaffoldQuote("TODO(owner): what a tenant is"))
	w("  workspace:\n    label: %s\n    description: %s\n", scaffoldQuote("TODO(owner): workspace"), scaffoldQuote("TODO(owner): what a workspace is"))
	w("  principal_kinds:\n  - human\n  roles:\n    todo_role:\n      description: %s\n", scaffoldQuote("TODO(owner): one entry per role of the application"))
	w("languages: # TODO(owner): the languages the application supports\n  default: en\n  supported:\n  - en\n")
	w("capabilities: # verified ids; each file is a stub the owner completes\n")
	for _, c := range p.caps {
		b.WriteString(scaffoldRefLines("  # ", c.Refs))
		w("  %s: %s\n", scaffoldQuote(c.ID), c.File)
	}
	if len(p.rag) == 0 {
		w("rag_sources: {} # no RAG source candidate was verified; TODO(owner): declare the sources the application wants answered from\n")
	} else {
		w("rag_sources: # candidates only: the owner decides whether each is a source at all\n")
		for _, r := range p.rag {
			b.WriteString(scaffoldRefLines("  # ", r.Refs))
			w("  %s: %s\n", scaffoldQuote(r.ID), r.File)
		}
	}
	w("model_requirements: # TODO(owner): the profile and models the application needs\n  minimum_profile: lite\n  controller:\n    need: required\n")
	w("retention: # TODO(owner): every period; 1 day is a placeholder, not a recommendation\n  session_state_days: 1\n  transcript_days: 1\n  action_receipt_days: 1\n  audit_days: 1\n  log_days: 1\n")
	w("network: # no destination is allowed until the owner lists it\n  default: deny\n  egress: {}\n")
	w("external:\n  forbid: true # the strictest choice: no external model provider; TODO(owner): relax only deliberately\n")
	w("integrity:\n  signature_manifest: signatures/signature-manifest.json\n  hash_algorithm: sha256\n  signature_algorithm: ed25519\n  publisher_key_ids:\n  - todo-owner-publisher-key\n")
	return b.String()
}

// scaffoldCapabilityYAML is one capability stub: the id, the strictest confirmation mode and TODO markers. risk_level and effect_class
// are deliberately absent: a zero value would read as "safe".
func scaffoldCapabilityYAML(p scaffoldPlan, c scaffoldCapability) string {
	var b strings.Builder
	b.WriteString(scaffoldYAMLMarker)
	b.WriteString("#\n")
	if len(c.Refs) > 0 {
		b.WriteString("# The id occurs in the files below (re-read and re-hashed when this draft was made). Confirm it is a capability.\n")
		b.WriteString(scaffoldRefLines("# ", c.Refs))
	} else {
		b.WriteString("# No capability could be confirmed from verified evidence. This id is a placeholder. TODO(owner): rename or delete.\n")
	}
	b.WriteString("#\n")
	b.WriteString("# TODO(owner): complete every item below, then validate with `alixai package validate`:\n")
	for _, t := range []string{
		"version, audience, title, purpose, scope_level, permissions",
		"fields, entity_types, ambiguity, validation, failure_states",
		"effect_class and risk_level: the owner's decision, deliberately not written here (risk 0 allows only confirmation mode none)",
		"operations: the read / validate / prepare / commit / status bindings, with their endpoint, tool or operation, and result schemas",
		"prepared_action and idempotency (required from risk level 1)",
		"response_obligations, next_actions, examples (test-only) and doc_refs into documentation/index.yaml",
	} {
		b.WriteString("#   - " + t + "\n")
	}
	fmt.Fprintf(&b, "id: %s\n", scaffoldQuote(c.ID))
	b.WriteString("confirmation: # the strictest mode; TODO(owner): lower it only to match the risk level you set\n  mode: step_up\n  step_up_channel: step_up_credential\n")
	return b.String()
}

func scaffoldDocIndex(p scaffoldPlan) string {
	var b strings.Builder
	b.WriteString(scaffoldYAMLMarker)
	b.WriteString("#\n# TODO(owner): one entry per capability, facet and language (field, validation_rule, permission, failure_state, risk_level,\n")
	b.WriteString("# confirmation_rule, user_visible_outcome), each pointing at a location in documentation/. The stubs to write them in:\n")
	for _, c := range p.caps {
		fmt.Fprintf(&b, "#   %s -> %s\n", scaffoldComment(c.ID), c.Doc)
	}
	b.WriteString("entries: []\n")
	return b.String()
}

func scaffoldCapabilityDoc(c scaffoldCapability) string {
	var b strings.Builder
	b.WriteString(scaffoldMDMarker)
	fmt.Fprintf(&b, "\n# %s\n\n", scaffoldComment(c.ID))
	b.WriteString("## Verified references\n\n")
	if len(c.Refs) == 0 {
		b.WriteString("- none: no capability was confirmed from verified evidence\n")
	}
	for _, r := range c.Refs {
		fmt.Fprintf(&b, "- `%s` lines %d-%d (sha256 `%s`)\n", scaffoldComment(r.Path), r.Start, r.End, r.SHA)
	}
	b.WriteString("\n## TODO(owner)\n\nWrite each section yourself; none of it was generated.\n\n")
	for _, s := range []string{"Purpose", "Fields and their validation rules", "Permissions", "Failure states", "Risk level", "Confirmation rule", "What the user sees on success"} {
		fmt.Fprintf(&b, "### %s\n\nTODO(owner)\n\n", s)
	}
	return b.String()
}

func scaffoldRAGYAML(r scaffoldRAG) string {
	var b strings.Builder
	b.WriteString(scaffoldYAMLMarker)
	b.WriteString("#\n# A candidate only: a folder that holds documents was found. Whether it is a RAG source is the owner's decision.\n")
	b.WriteString(scaffoldRefLines("# ", r.Refs))
	b.WriteString("#\n# TODO(owner): type, owner, scope, root, include, exclude, credential_ref, formats, limits, sync, deletion, parser, citation, retention.\n")
	fmt.Fprintf(&b, "id: %s\n", scaffoldQuote(r.ID))
	b.WriteString("classification: restricted # the strictest class; TODO(owner): lower it only on purpose\n")
	b.WriteString("egress_mode: local_only # content never leaves the machine; TODO(owner): change only on purpose\n")
	b.WriteString("egress: # no network destination is allowed\n  entries: []\n")
	return b.String()
}

func scaffoldTodo(p scaffoldPlan) string {
	var b strings.Builder
	b.WriteString(scaffoldMDMarker)
	b.WriteString("\n# DRAFT package: what the application owner must complete and sign\n\n")
	b.WriteString("This directory is a **draft**. It is not signed, it is not an installable package and it does not certify anything.\n")
	b.WriteString("The package loader refuses it as unsigned, and an installed copy would be quarantined. A complete draft is not an audit pass:\n")
	b.WriteString("the integration audit still decides activation. Delete this file before you sign the package.\n\n")
	fmt.Fprintf(&b, "It was made from readiness report `%s`, using only findings that are found or partial with evidence that was re-read and re-hashed.\n\n", scaffoldComment(p.reportID))
	b.WriteString("## What you must do\n\n")
	for _, s := range []string{
		"`alixai.yaml`: replace every `TODO(owner)` value and every `.invalid` host; set the versions, endpoints, context exchange, tenancy, languages, model needs, retention, network egress and publisher key",
		"`capabilities/`: complete each stub (see the TODO list inside it); decide the risk level and effect class yourself; the draft sets no risk level and the strictest confirmation mode",
		"`documentation/`: write the documentation yourself (the files are stubs with the verified references) and fill `documentation/index.yaml` so every capability has every facet",
		"`rag-sources/`: decide whether each candidate is a source and complete its declaration (classification restricted and egress local_only are the strictest defaults)",
		"Not generated at all, still required: `conversation-contracts/` (one per capability and language), `policies/`, `terminology/`, `schemas/` (result schemas and adapter configurations), `tests/` (including the safety probes)",
		"`signatures/`: sign the finished package with `alixai package sign`, then check it with `alixai package validate`",
	} {
		b.WriteString("- [ ] " + s + "\n")
	}
	b.WriteString("\n## Capabilities with a stub\n\n")
	for _, c := range p.caps {
		fmt.Fprintf(&b, "- `%s` in `%s` (documentation stub `%s`)\n", scaffoldComment(c.ID), c.File, c.Doc)
	}
	if p.placeholder {
		b.WriteString("\nNo capability could be confirmed from verified evidence; the one stub is a placeholder.\n")
	}
	if len(p.candidates) > 0 {
		b.WriteString("\n## Names found in verified files that are not capability ids\n\nThe owner decides which capability, if any, each one belongs to.\n\n")
		for _, c := range p.candidates {
			fmt.Fprintf(&b, "- %s `%s`: %s\n", c.Kind, scaffoldComment(c.Name), scaffoldComment(c.Refs[0].ref()))
		}
	}
	if len(p.gaps) > 0 {
		b.WriteString("\n## Requirements with no verified evidence in this draft\n\n")
		b.WriteString("Listed by id only. The scan report says what to do about each; this draft takes nothing from them.\n\n")
		for _, g := range p.gaps {
			fmt.Fprintf(&b, "- `%s` (%s, feeds %s)\n", scaffoldComment(string(g.RequirementID)), g.Level, scaffoldComment(string(g.CheckID)))
		}
	}
	return b.String()
}
