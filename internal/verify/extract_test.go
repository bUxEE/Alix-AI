package verify

import "testing"

func TestExtractReadings(t *testing.T) {
	tests := []struct {
		name string
		lang Language
		text string
		want string
	}{
		{"integer", LangEN, "You have 24 hours", "n:24"},
		{"iso date", LangEN, "on 2026-10-14", "d:2026-10-14"},
		{"day month year en", LangEN, "on 14 October 2026", "d:2026-10-14"},
		{"month day year en", LangEN, "on October 14, 2026", "d:2026-10-14"},
		{"ordinal en", LangEN, "on the 14th of October", "d:????-10-14"},
		{"italian date", LangIT, "il 14 ottobre 2026", "d:2026-10-14"},
		{"italian abbreviation", LangIT, "il 14 ott 2026", "d:2026-10-14"},
		{"slash it dmy", LangIT, "il 04/05/2026", "d:2026-05-04"},
		{"slash en day over 12", LangEN, "on 14/10/2026", "d:2026-10-14"},
		{"slash en month first", LangEN, "on 10/14/2026", "d:2026-10-14"},
		{"slash en ambiguous keeps both", LangEN, "on 04/05/2026", "d:2026-05-04+d:2026-04-05"},
		{"dotted date", LangIT, "il 14.10.2026", "d:2026-10-14"},
		{"time 24h", LangEN, "at 10:30", "t:10:30"},
		{"time pm", LangEN, "at 10:30 pm", "t:22:30"},
		{"time pm attached", LangEN, "at 10:30pm", "t:22:30"},
		{"hour am", LangEN, "at 10 am", "t:10:00"},
		{"italian dot time or decimal", LangIT, "alle 10.30", "n:10.3|t:10:30"},
		{"italian h time", LangIT, "alle 10h30", "t:10:30"},
		{"noon", LangEN, "at noon", "t:12:00"},
		{"en decimal also reads as a time", LangEN, "costs 12.50", "n:12.5|t:12:50"},
		{"dot time with pm", LangEN, "at 10.30 pm", "t:22:30"},
		{"it decimal", LangIT, "costa 12,50", "n:12.5"},
		{"en thousands", LangEN, "costs 1,234.56", "n:1234.56"},
		{"it thousands", LangIT, "costa 1.234,56", "n:1234.56"},
		{"en 1.234 is a decimal", LangEN, "1.234", "n:1.234"},
		{"it 1.234 is 1234", LangIT, "1.234", "n:1234"},
		{"en 1,234 is 1234", LangEN, "1,234", "n:1234"},
		{"it 1,234 is a decimal", LangIT, "1,234", "n:1.234"},
		{"it 0.500 is not 500", LangIT, "0.500", "n:0.5"},
		{"en 0,500 is not 500", LangEN, "0,500", "n:0.5"},
		{"it 0.500.000 is not 500000", LangIT, "0.500.000", "n:0+n:500+n:0"},
		{"nbsp thousands", LangIT, "costa 1\u00a0250,50", "n:1250.5"},
		{"money symbol first", LangEN, "costs €12.50", "m:12.5EUR"},
		{"money symbol after it", LangIT, "costa 12,50 €", "m:12.5EUR"},
		{"money nbsp symbol", LangIT, "costa 12,50\u00a0€", "m:12.5EUR"},
		{"money word", LangEN, "costs 50 euros", "m:50EUR"},
		{"money code first", LangEN, "costs EUR 50", "m:50EUR"},
		{"money code after", LangEN, "costs 50 USD", "m:50USD"},
		{"money dollar", LangEN, "costs $12.50", "m:12.5USD"},
		{"money attached code", LangEN, "costs 50eur", "m:50EUR"},
		{"two amounts keep their own currency", LangEN, "€5 and $6", "m:5EUR m:6USD"},
		{"number words en", LangEN, "twenty-four hours", "n:24"},
		{"number words en phrase", LangEN, "two hundred and fifty", "n:250"},
		{"number words it", LangIT, "ventiquattro ore", "n:24"},
		{"number words it hundreds", LangIT, "duecentocinquanta", "n:250"},
		{"number words it thousands", LangIT, "duemilacinquecento", "n:2500"},
		{"number words it accents", LangIT, "ventitré", "n:23"},
		{"lone one is not a number", LangEN, "one of the options", ""},
		{"un uno una are articles", LangIT, "un momento, una volta, uno", ""},
		{"sei is a verb", LangIT, "sei sicuro?", ""},
		{"due is a word in english", LangEN, "the due date", ""},
		{"due is two in italian", LangIT, "due appuntamenti", "n:2"},
		{"compound with uno", LangIT, "ventuno", "n:21"},
		{"identifier", LangEN, "your id is apt_20991.", "id:apt_20991"},
		{"identifier dashed", LangEN, "INV-2024-0042 is open", "id:INV-2024-0042"},
		{"url", LangEN, "see https://example.com/a?b=1 now", "id:https://example.com/a?b=1"},
		{"email", LangEN, "write to a@b.example", "id:a@b.example"},
		{"typed id", LangEN, "ref ses_01J0000000000000000000000A", "id:ses_01J0000000000000000000000A"},
		{"list markers are not numbers", LangEN, "1. first\n2. second\n3) third", ""},
		{"nested list markers", LangEN, "1. a\n   1. x\n   2. y\n2. b", ""},
		{"a list that resumes after a paragraph", LangEN, "1. a\n2. b\n\nThen:\n3. c", ""},
		{"repeated list markers", LangEN, "1. a\n1. b\n1. c", ""},
		{"a number out of sequence is not a list marker", LangEN, "Temp 5\n50. blah", "n:5 n:50"},
		{"citation index", LangEN, "as stated [2]", "cite"},
		{"citation id", LangEN, "as stated [src_01J0000000000000000000000A]", "cite"},
		{"scale suffix", LangEN, "costs 5k", "n:5000"},
		{"scale suffix with a currency", LangEN, "costs €2.5k", "m:2500EUR"},
		{"italian scale word", LangIT, "costa 5 mila euro", "m:5000EUR"},
		{"italian scale attached", LangIT, "costa 1,5mln", "n:1500000"},
		{"italian millions", LangIT, "5 milioni di euro", "n:5000000"},
		{"english scale word", LangEN, "2 million", "n:2000000"},
		{"english billion", LangEN, "3 billion", "n:3000000000"},
		{"number word and scale word", LangIT, "cinque milioni", "n:5000000"},
		{"metres are not a scale", LangEN, "5 m away, 5m wide", "n:5 n:5"},
		{"percent", LangEN, "20% off", "n:20"},
		{"negative", LangEN, "balance -5", "n:-5"},
		{"negative after a no-break space", LangEN, "balance -5", "n:-5"},
		{"range", LangEN, "10-12 items", "n:10 n:12"},
		{"time range", LangEN, "10:30-11:00", "t:10:30 t:11:00"},
		{"weekday alone", LangEN, "on Tuesday", "wd:2"},
		{"weekday with date", LangEN, "Wednesday 14 October 2026", "d:2026-10-14+wdd:3/2026-10-14"},
		{"italian weekday", LangIT, "mercoledì 14 ottobre", "d:????-10-14+wdd:3/????-10-14"},
		{"weekday abbreviation with date", LangEN, "Wed 14 October 2026", "d:2026-10-14+wdd:3/2026-10-14"},
		{"weekday abbreviation with a dot and a comma", LangEN, "Mon., 14 Oct 2026", "d:2026-10-14+wdd:1/2026-10-14"},
		{"italian weekday abbreviation", LangIT, "lun 14 ottobre 2026", "d:2026-10-14+wdd:1/2026-10-14"},
		{"weekday abbreviations are words without a date", LangEN, "the sun is out, I sat down on Wed", ""},
		{"weekday abbreviation not before a date", LangEN, "sat 3 times", "n:3"},
		{"month alone", LangEN, "in October", "d:????-10-??"},
		{"may is a verb", LangEN, "you may cancel", ""},
		{"may with a day", LangEN, "on 14 May", "d:????-05-14"},
		{"month and year", LangEN, "in October 2026", "d:2026-10-??"},
		{"completion", LangEN, "your appointment is booked", "done"},
		{"completion negated", LangEN, "your appointment was not booked", ""},
		{"completion negated by contraction", LangEN, "it couldn't be saved", ""},
		{"completion quantifier negation", LangEN, "no changes were saved", ""},
		{"completion italian", LangIT, "è stato prenotato", "done"},
		{"completion italian negated", LangIT, "non è stato prenotato", ""},
		{"completion across a clause", LangEN, "I did not wait, it is booked", "done"},
		{"base form is not a claim", LangEN, "please confirm and book", ""},
		{"fullwidth digits", LangEN, "\uff12\uff14 hours", "n:24"},
		{"zero width split", LangEN, "2\u200b4 hours", "n:24"},
		{"arabic indic digits", LangEN, "\u0662\u0664 hours", "n:24"},
		{"superscript", LangEN, "note \u00b2", "n:2"},
		{"roman numeral is unknown", LangEN, "chapter \u216b", "?"},
		{"instant", LangEN, "2026-10-14T08:30:00Z", "i:2026-10-14T08:30:00Z"},
		{"instant with offset", LangEN, "2026-10-14T10:30:00+02:00", "i:2026-10-14T08:30:00Z"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := readings(tt.text, tt.lang); got != tt.want {
				t.Errorf("readings(%q, %s) = %q, want %q", tt.text, tt.lang, got, tt.want)
			}
		})
	}
}
