// Package realtime is the LocalAI Realtime adapter of master plan section 13:
// "LocalAI Realtime may provide the model pipeline". It speaks the runtime's
// OpenAI-compatible Realtime WebSocket, but only for the audio-in half of the
// voice loop: VAD and STT, producing finalised transcript text that enters the
// normal AlixAI turn pipeline like typed text. It is never a side door: the
// runtime does not answer, call tools or speak on its own, and AlixAI keeps all
// authority. Like the rest of adapters/localai it is the only code that knows
// LocalAI exists.
//
// Client implements voice.STT (Transcribe and TranscribeStream). Speech pairs it
// with the separate STT and TTS adapters (adapters/localai/voice) and is what a
// composition root registers for the STT and TTS roles.
//
// # Pinned runtime
//
// Read on 2026-10-07 from the LocalAI v4.10.0 sources (the version pinned by
// deploy/container/localai):
//
//   - https://github.com/mudler/LocalAI/blob/v4.10.0/core/http/endpoints/openai/realtime.go
//     (handshake, session.update handling, commit, the VAD loop, the transcription
//     path and the response path)
//   - https://github.com/mudler/LocalAI/blob/v4.10.0/core/http/endpoints/openai/types/
//     (client and server event types, session and turn-detection shapes)
//   - https://github.com/mudler/LocalAI/blob/v4.10.0/core/http/routes/openai.go
//     (GET /v1/realtime, and the sibling /sessions, /transcription_session and /calls)
//
// # No side door
//
// Four layers, each tested (SEC-070, SEC-094):
//
//  1. The session is a transcription session. The first and only configuration
//     event is session.update with session.type "transcription": the runtime
//     routes it to its transcription-only path, which has no answering stage, and
//     reports it back as a "transcription" session. The adapter sends no audio
//     until that confirmation arrives, and refuses a session that confirms any
//     other type.
//  2. The configuration also carries tool_choice "none", an empty tool list and
//     turn detection that is either null (the client commits) or server VAD with
//     create_response and interrupt_response both off, in case a runtime ignores
//     the session type.
//  3. The client never sends response.create, conversation.item.create or any
//     tool-result event. It sends session.update, input_audio_buffer.append,
//     .commit and .clear, and nothing else.
//  4. A tripwire: any response.*, function-call, MCP or assistant-item event is a
//     violation. The stream closes at once with an internal error carrying the
//     reason "model_side_door", nothing the runtime said is relayed, and the
//     fallback does not run (it is not unavailability).
//
// The upgrade request is allowlisted like every other LocalAI call (see
// AllowedEndpoints): GET /v1/realtime with the single query parameter "model".
// localai_assistant, which would switch on the runtime's in-process management
// tools, any other parameter, the sibling routes and every other route are
// refused in the transport before any I/O; redirects are never followed, the
// connection is proxy-free and loopback-only for plaintext, and the API key is
// attached there and only there.
//
// # Streams
//
// In the default manual mode the whole stream is one utterance: Send appends
// audio, CloseSend commits it, and the runtime answers with transcription delta
// events (relayed as interim events carrying the text so far) and one completed
// event (the final event), then Done. The runtime refuses a manual commit while
// its own turn detection is active, so Config.ServerVAD is a separate mode: the
// runtime cuts utterances itself, every completed utterance is a final segment,
// and CloseSend appends a tail of silence and waits Config.SettleTimeout for the
// last one. The transcript is complete only when Done arrived; a cut connection,
// an error event, a failed transcription or a deadline is an error and the text
// received so far is partial and never returned as a success. CloseSend with no
// audio yields an empty complete transcript (silence).
//
// # Cancellation
//
// Close drops the WebSocket, which stops the runtime's work for the session at
// once, and unblocks a waiting Recv (providers.ErrStreamClosed). Cancelling or
// timing out the context given to TranscribeStream does the same and Recv
// returns the context's error (a deadline is a timeout). One reader goroutine
// per stream exists, and it ends with the stream.
//
// # Text to speech is not served here
//
// LocalAI's Realtime has no verbatim speech path: a response is always
// generated by the model (response.create, with or without items, reaches
// Predict). Speaking "verified text" through it would let the model choose the
// words, which is exactly what master plan sections 3 and 13 forbid. So Client
// has no TTS method, and Speech sends every SynthesizeStream to the separate TTS
// adapter. Revisit if a future LocalAI exposes a speak-this-text event.
//
// # Fallback
//
// Speech falls back to the separate STT adapter only when the Realtime pipeline
// is unavailable at the open (connection refused, no realtime route, a runtime
// that cannot run a transcription-only session), or, for a batch Transcribe,
// when the connection is lost part way (the caller still holds the audio). It
// never falls back on cancellation, a deadline, a validation, scope or limit
// error, resource exhaustion, a stream that already carried audio, or a
// side-door violation. Each fall back is logged and reported to a hook.
//
// # Privacy and errors
//
// Audio never leaves the machine (endpoint policy), is never written to disk by
// this package and is never logged; transcripts, runtime messages and the key are
// never copied into errors or logs. Failures are *contracts.Error values:
// unavailable (cannot connect or configure, connection lost), timeout,
// resource_exhausted (the runtime's buffer or memory limits), schema_invalid
// (malformed events), validation_failed (the request), internal (rejected key,
// violation). The adapter never retries.
