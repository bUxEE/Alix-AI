"""The generated models against the schemas they come from: no drift, and every valid example of the schemas parses."""

from __future__ import annotations

import importlib
import json
from pathlib import Path
from typing import Any

import pytest
from pydantic import TypeAdapter

import gen_models  # tools/gen_models.py, put on the path by conftest
from alixai import ERROR_CODES
from alixai.errors import RETRYABLE_CODES
from tests.helpers.openapi import SCHEMAS_DIR

pytestmark = pytest.mark.skipif(not SCHEMAS_DIR.is_dir(), reason="schemas/ is not next to this package (an sdist install)")


def test_the_committed_models_are_what_the_schemas_generate() -> None:
    """The drift check, as tools/schemagen has one for Go and TypeScript: edit schemas/, run tools/gen_models.py."""
    files = gen_models.build()
    stale = [str(p.relative_to(gen_models.SDK_ROOT)) for p, text in files.items() if not p.exists() or p.read_bytes().replace(b"\r\n", b"\n") != text.encode("utf-8")]
    extra = [str(p.relative_to(gen_models.SDK_ROOT)) for p in gen_models.existing() - set(files) if "__pycache__" not in str(p)]
    assert stale == [] and extra == [], "run `python tools/gen_models.py` and commit the result"


def test_generated_files_say_they_are_generated_and_are_not_hand_edited() -> None:
    for path in gen_models.GEN_DIR.rglob("*.py"):
        assert path.read_text(encoding="utf-8").startswith("# Code generated by tools/gen_models.py"), path


