// Command voicebench measures the voice models of the Lite profile (master plan 7.1, 13, 25 item 6, task M4-06): word error rate per
// language, real-time factor, time to first audio, worker resident set and non-speech behaviour of speech to text, text to speech and
// voice activity detection, through the real adapter adapters/localai/voice against a LocalAI the caller started under
// compose.lite.yaml (the tool never starts a container; tests/performance/voice/stack/ does).
//
//	voicebench fetch-fleurs  -out DIR -manifest FILE [-n 40]        download the pinned FLEURS clips (CC-BY-4.0) and write the manifest
//	voicebench run -phase stt|vad|tts ...                            one candidate, one phase, one result file (.voice)
//	voicebench check DIR...                                          validate .voice files and re-derive every aggregate from the records
//	voicebench verdict -results DIR -out FILE                        apply the pre-registered gates of docs/evidence/m4-voice/protocol.md
//	voicebench companion -vad FILE -out DIR                          write the bench-envelope companion (.json) that `bench check` accepts
//
// Results are emulated (resource-limited container on a larger machine), never certified. Audio is never committed: the FLEURS
// manifest pins every clip by sha256, the non-speech clips are generated deterministically, TTS audio is regenerated by the run.
