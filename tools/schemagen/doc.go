// Command schemagen generates the Go and TypeScript types of every schema area
// under schemas/ and checks that the committed output is current:
//
//	go run ./tools/schemagen            write pkg/contracts/gen (Go) and sdk/typescript/src/gen (TypeScript)
//	go run ./tools/schemagen --check    write nothing; exit 1 when committed output is stale
//
// Flags: -root (default: nearest ancestor holding go.mod and schemas/),
// -schemas, -go-out and -ts-out. Exit status: 0 ok, 1 stale output or a schema
// the generator cannot represent, 2 usage error.
//
// Schemas are the contract (master plan section 6, "JSON Schema plus generated
// language types"); the generated types are never edited by hand. Every area
// found under schemas/ (a directory holding *.schema.json files) is generated,
// so a task that adds a schema re-runs this tool and commits the result.
//
// # Output
//
// Go: one package per area, schemas/<area> -> pkg/contracts/gen/<area without
// hyphens>, one file per schema (task_proposal.gen.go) plus doc.gen.go. The
// packages import only the standard library and each other, never
// pkg/contracts, so pkg/contracts can alias their types (aliases.go).
//
// TypeScript: schemas/<area>/<name>.schema.json ->
// sdk/typescript/src/gen/<area>/<name>.ts, an index.ts per area and one at the
// root exporting one namespace per area. Plain ESM, import type only, no runtime.
//
// Generated files start with "// Code generated by tools/schemagen ... DO NOT
// EDIT." Output is a pure function of the schema files: no timestamps, no
// absolute paths, no map-order dependence. --check also reports generated files
// that nothing produces any more; files without the header (tests, doc.go) are
// never read as generated and never deleted.
//
// # What the types express, and what they leave to the schema
//
// The types carry shape: members, required or optional, nullable, enums,
// const members, discriminated unions, maps keyed by propertyNames. They do
// not carry constraints they cannot state (patterns, lengths, ranges,
// uniqueItems) or cross-field rules (if/then/else, required alternatives,
// dependentRequired): those are overlays, the generated type is the loose one,
// and runtime schema validation stays authoritative. A struct that has overlays
// says so in its documentation. What the Go types do enforce, because it is
// cheap and fails closed: enums and union discriminators reject unknown values
// and null on decode and refuse to encode an unset value; const members are
// forced on encode; required arrays and maps never encode as null.
//
// # Schema constructs
//
//	$ref to a $defs entry, same file or another      the declaration of that entry
//	$ref into /properties/<name> of another file     a declaration named after the location (common.ErrorCode)
//	anyOf/oneOf [X, null]                            nullable X (Go pointer, TS "X | null")
//	oneOf of objects with a distinct string const    a union: Go struct holding an interface, TS union
//	oneOf/anyOf without such a discriminator         Go any, TS union of the members
//	allOf of the same primitive type                 that primitive
//	if/then/else, not, contains, dependentRequired,  ignored (overlays)
//	  required-only oneOf/anyOf/allOf members
//	object with properties                           struct / interface
//	object with propertyNames + additionalProperties map[string]V / Record<string, V>
//	enum, const                                      named enum type, literal
//
// A member of oneOf/anyOf/allOf is type-bearing only if it has $ref, type,
// const or enum; anything else is an overlay. A construct that fits no row (a
// type-bearing allOf of different types, patternProperties, an object with both
// properties and an additionalProperties schema, a union variant in another
// area, two schemas producing one name, areas that import each other) is an
// error, not a guess.
//
// # Names
//
// A schema root is PascalCase(file name): task-proposal.schema.json -> TaskProposal.
// A $defs entry of a schema whose root is an object is prefixed with the root
// (TaskProposalEntityRef); entries of definition libraries and of union roots
// keep their own name (Fact, TokenEvent). Names therefore depend only on the
// schema they come from: adding a schema never renames the types of another.
// Properties and enum values extend the name of their parent (ErrorCode,
// DoneEventFinishReason). A clash is reported, never silently resolved. The
// TypeScript output aliases an import that would clash with a local name
// (ErrorCode as CommonErrorCode).
//
// # Why a purpose-built generator
//
// The generators that exist were evaluated against these schemas (October 2026)
// and none handled them:
//
//   - github.com/atombender/go-jsonschema v0.24.1 (the Go generator;
//     the omissis fork declares the same module path) fails with "unsupported $ref
//     schema" on the first urn:alixai:schema reference, with or without every
//     schema file on the command line.
//   - json-schema-to-typescript 16.0.0 works only through a custom resolver for
//     the urn: references, emits 2,127 lines for turn-event.schema.json alone,
//     numbers colliding names (TurnID, TurnID1, TurnID2, FieldName1), types a
//     closed object as an intersection with an index signature, and needs node
//     and an npm install at generation time. Neither Go tests nor go run may
//     depend on that: they must be hermetic.
//
// One small generator covers both languages from a single model, resolves the
// urn: references exactly like tools/schemacheck, stays offline, and fails on
// schema shapes it does not understand instead of generating something close.
